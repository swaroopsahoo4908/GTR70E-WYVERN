"""Generate fc100_board.h from the KiCad netlist (_design.json + symbol pin names)."""
import json,re,sys
d=json.load(open('/tmp/w/out/FC100/_design.json'))
sym=open('/tmp/w/out/FC100/WYVERN_FC100.kicad_sym').read()
i=sym.find('(symbol "RP2350B'); j=sym.find('\n(symbol "',i+1)
pn={n:nm for nm,n in re.findall(r'\(name "([^"]*)".*?\(number "([^"]*)"',sym[i:j])}
gp={}
for k,net in d['nets'].items():
    r,n=k.split('.',1)
    if r!='U1': continue
    m=re.match(r'GPIO(\d+)',pn.get(n,''))
    if m: gp[net]=int(m.group(1))
def g(net): return gp[net]
servo=['SERVO_U19','SERVO_U23','SERVO_U24','SERVO_U25','SERVO_U26','SERVO_U27','SERVO_U28','SERVO_U29','SERVO_U30']
hdr=[f'HDR_P{i}' for i in range(1,13)]
o=[]
w=o.append
w('#pragma once')
w('// =================================================================================================')
w('// WYVERN-E FC-100 rev 3 (JLCPCBA release) -- board pin map for arduino-pico (earlephilhower core).')
w('// GENERATED from the KiCad netlist by tools/gen_fwpins.py. Do not hand-edit: re-run after any schematic change.')
w('// Target: RP2350B QFN-80. 16 MB W25Q128 on QMI CS0, 8 MB APS6404L PSRAM on QMI CS1.')
w('// Board menu: "Generic RP2350", Flash 16MB, PSRAM 8MB, PSRAM CS = %d (or -DRP2350_PSRAM_CS=%d).' % (g('PSRAM_CS'),g('PSRAM_CS')))
w('// =================================================================================================')
w('')
w('// ---- I2C0: sensor bus')
w(f"#define FC_I2C0_SDA        {g('I2C0_SDA_SENS')}")
w(f"#define FC_I2C0_SCL        {g('I2C0_SCL_SENS')}      // 4.7k pull-ups R36/R37")
for n,a,c in [('LIS3MDL',0x1C,'SA1 = GND'),('LSM9DS1_M',0x1E,'SDO_M = 3V3'),('BNO055',0x28,'COM3 = GND'),('LPS22HB',0x5C,'SA0 = GND'),('LSM9DS1_AG',0x6A,'SDO_A/G = GND'),('BME680',0x76,'SDO = GND')]:
    w(f"#define FC_ADDR_{n:<11}0x{a:02X}    // {c}")
w('')
w('// ---- I2C1: system bus')
w(f"#define FC_I2C1_SDA        {g('I2C1_SDA')}")
w(f"#define FC_I2C1_SCL        {g('I2C1_SCL')}      // 4.7k pull-ups R38/R39")
for n,a,c in [('MCP23008',0x20,'A2..A0 = GND'),('ADAU1450',0x38,'ADDR1/0 = GND, SELFBOOT = GND (host loads program over I2C)'),('INA_BATT',0x40,'U8, 10 mOhm R3 in the pack lead'),('INA_SERVO',0x41,'U9, A0 = VS, 10 mOhm R7 in VSERVO'),('BQ25798',0x6B,'charger')]:
    w(f"#define FC_ADDR_{n:<11}0x{a:02X}    // {c}")
w('#define FC_INA_SHUNT_OHM   0.010f')
w('')
w('// ---- microSD on SPI0')
w(f"#define FC_SD_MISO         {g('SD_MISO')}      // SPI0 RX")
w(f"#define FC_SD_CS           {g('SD_CS')}")
w(f"#define FC_SD_SCK          {g('SD_SCK')}")
w(f"#define FC_SD_MOSI         {g('SD_MOSI')}      // SPI0 TX")
w(f"#define FC_SD_CD           {g('SD_CD')}      // card detect, 20k pull-up R6")
w('')
w('// ---- servo / actuator outputs, JST-XH 3P (SIG, VSERVO 5.0 V, GND). Order = connector reference order.')
w('// U19, U23, U24, U25, U26, U27, U28, U29, U30. Every RP2350 GPIO has a PWM channel.')
w('static const uint8_t FC_SERVO_PINS[9] = {' + ', '.join(str(g(s)) for s in servo) + '};')
w(f"#define FC_SERVO_PITCH     {g('SERVO_U19')}      // U19")
w(f"#define FC_SERVO_YAW       {g('SERVO_U23')}      // U23")
w('')
w('// ---- H1 1x14 header: pins 1..12 = GPIO below, pin 13 = 3V3, pin 14 = SWDIO. SWCLK on test pad TP1.')
w('static const uint8_t FC_HDR_PINS[12] = {' + ', '.join(str(g(h)) for h in hdr) + '};  // H1 pin 1..12')
w(f"// U20 1x4: GPIO{g('AUX_P1')}, GPIO{g('AUX_P2')}, 3V3, GND")
w(f"#define FC_AUX1            {g('AUX_P1')}")
w(f"#define FC_AUX2            {g('AUX_P2')}")
w(f"// U31 1x4: GPIO{g('GPIO43_ADC3')} (ADC3), GPIO{g('GPIO44_ADC4')} (ADC4), 3V3, GND")
w(f"// U32 1x4: GPIO{g('GPIO45_ADC5')} (ADC5), GPIO{g('GPIO46_ADC6')} (ADC6), GPIO{g('GPIO40_ADC0')} (ADC0), GND")
w('')
w('// ---- status, interrupts, audio')
w(f"#define FC_LED1            {g('LED1_DRV')}      // active HIGH, 330R")
w(f"#define FC_MCP_INT         {g('U12_INT')}")
w(f"#define FC_DSP_RESET       {g('DSP_RESET')}      // ADAU1450 RESET, active LOW")
w(f"#define FC_PDM_CLK         {g('PDM_CLK')}      // IM63D135 CLK + ADAU1450 BCLK_IN0 (PIO-driven)")
w(f"#define FC_PDM_DATA        {g('PDM_DATA')}      // IM63D135 DATA (L/R = GND) + ADAU1450 SDATA_IN0")
w(f"#define FC_DSP_LRCLK       {g('DSP_LRCLK')}      // ADAU1450 LRCLK_IN0")
w(f"#define FC_LSM9DS1_INT1    {g('U14_NT1_A')}")
w(f"#define FC_BNO055_INT      {g('U15_INT')}")
w(f"#define FC_BQ_INT          {g('U3_INT')}      // open drain: enable the internal pull-up")
w(f"#define FC_PSRAM_CS        {g('PSRAM_CS')}      // QMI CS1n (only GPIO0/8/19/47 can carry it)")
w('')
w('// ---- MCP23008 pyro channels (recovery is motor ejection; keep disarmed unless deliberately used)')
w('#define FC_MCP_PYRO1_DRV   0       // GP0 -> 1k -> AO3400A Q1 gate, 10k pull-down')
w('#define FC_MCP_PYRO2_DRV   1')
w('#define FC_MCP_PYRO1_CONT  2       // GP2 <- 33k/10k divider from channel output, 3V3 zener clamp')
w('#define FC_MCP_PYRO2_CONT  3')
w('')
w('// ---- power (rev 3): USB-C 5 V (5.1k Rd, no PD) or 2S pack (XT30) -> BQ25798 (PROG 8.2k: 2S, 750 kHz)')
w('//      -> VSYS -> TPS563201 3V3 (EN tied to VSYS) and TPS54202 VSERVO 5.0 V; AMS1117-1.2 for ADAU1450 DVDD.')
w('#define FC_VBAT_WARN_V     6.4f')
w('#define FC_VBAT_CRIT_V     6.0f')
open(sys.argv[1],'w').write('\n'.join(o)+'\n')
print('ok',len(gp))
