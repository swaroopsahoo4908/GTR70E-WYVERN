//         board "Raspberry Pi Pico 2W", CPU 150 MHz, USB stack "Pico SDK"
// Libs  : Adafruit BNO08x, Adafruit BME680, SdFat - Adafruit Fork. The BMP388 driver is in baro.h
//         (register-level, non-blocking), so no BMP3XX library is needed.
// Rev 4b: Pico 2 W + Adafruit 4682 microSD breakout on SPI0 (was the Teensy 4.1 with its own socket).
//         Still no radio, no ground station, no high-g accelerometer; a pushbutton through the wall arms
//         the rocket and the card is the only record.
//
// Every numeric gain / limit below is generated by the simulation suite, not hand-tuned:
//   Simulations/plots_flight/tuned_gains.json   (kp, ki, kd, q_ref, schedule clamp)
//   Simulations/plots_authority/authority_matrix.json  (axis-B gain scale, hinge loads)
//   Simulations/canonical_numbers.json          (masses, stations, motor timing)
// If those change, update this file in the same commit.
