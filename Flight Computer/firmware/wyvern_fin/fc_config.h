#include <Arduino.h>

#define WYV_FW_VERSION "wyvern_fin 2.1.0 (Pico 2 W)"

// ------------------------------------------------------------------------------------- I2C, two buses
// The RP2350 has two I2C blocks. The BNO085 gets I2C0 to itself so a baro transaction can never sit
// between two IMU reads; both barometers share I2C1. They both default to 0x77, so the BMP388's ADDR
// solder jumper is closed (-> 0x76). At 400 kHz a BMP388 read is ~0.3 ms, a BME688 read ~0.6 ms.
//   Wire  (I2C0): SDA GP4, SCL GP5  -> BNO085 0x4A   (Adafruit 4754)
//   Wire1 (I2C1): SDA GP2, SCL GP3  -> BMP388 0x76   (Adafruit 3966, ADDR jumper closed; primary altimeter, 50 Hz)
//                                   -> BME688 0x77   (Adafruit 5046, temperature / humidity / density, 10 Hz)
#define WYV_I2C            Wire
#define WYV_PIN_SDA        4
#define WYV_PIN_SCL        5
#define WYV_I2C_BARO       Wire1
#define WYV_I2C_ENV        Wire1
#define WYV_PIN_SDA1       2
#define WYV_PIN_SCL1       3
#define WYV_I2C_HZ         400000UL
#define WYV_ADDR_BNO085    0x4A      // Adafruit 4754 default (DI/ADR pin open)
#define WYV_ADDR_BMP388    0x76      // Adafruit 3966 with the ADDR jumper closed
#define WYV_ADDR_BME688    0x77      // Adafruit 5046 default (SDO high)
#define WYV_PIN_BNO_INT    6         // BNO085 INT (data-ready, active low)
#define WYV_PIN_BNO_RST    7         // BNO085 RST (Adafruit recommends wiring it)

// ------------------------------------------------------------------------------------- SPI0, microSD
// Adafruit 4682 (3 V only, no level shifter: the Pico is 3.3 V logic, so it connects directly).
#define WYV_SD_SPI         SPI
#define WYV_PIN_SD_MISO    16        // 4682 DO
#define WYV_PIN_SD_CS      17        // 4682 CS
#define WYV_PIN_SD_SCK     18        // 4682 CLK
#define WYV_PIN_SD_MOSI    19        // 4682 DI
#define WYV_SD_MHZ         24        // SPI clock; drop to 12 if a card misbehaves on the t3 soak
// The BNO085 sits on the avionics spine's +X face, the lowest board (just above the servo ring),
// about 10 mm off the axis (the bypass tube owns the centreline). Rates are unaffected; the
// accelerometer picks up w_roll^2 * 10 mm of lateral acceleration, ~1.6 m/s^2 at 2 rev/s. Only the
// vertical channel uses accel in flight, and it is rotated into the world frame first.
#define WYV_IMU_OFFSET_MM  10.0f

// ------------------------------------------------------------------------------------- axial channel
// The BNO085 accelerometer saturates at +/-8 g. The F42-4T's first ~0.2 s pushes the specific force
// to ~8.9 g (68.7 N on 0.784 kg), so while the axial reading sits at the clip the channel takes the
// larger of the measurement and a thrust-curve model, (T(t) - qbar*CdA) / m(t). The model is the
// AeroTech F42T .eng (Simulations/motors/AeroTech_F42T.eng), propellant burned in proportion to impulse.
// Left uncorrected, the clip would bias the climb rate ~1 m/s low (2-4 % of qbar at max-q) until the
// baro pulls it back; with the model the bias is gone and what remains is the motor's own thrust
// scatter, ~0.17 m/s per 1 % thrust deviation over the clipped window.
#define WYV_ACCEL_CLIP_G   7.8f
#define WYV_M_LIFTOFF_KG   0.7837f   // canonical_numbers.json (rev 4)
#define WYV_M_PROP_KG      0.027f
#define WYV_CDA_M2         0.00098f  // Cd 0.37 x A 2.64e-3 m^2 (wf_core.cd_total at 40 m/s, boost)
static const float WYV_THRUST_T[] = { 0.0f, 0.01f, 0.029f, 0.202f, 0.511f, 0.739f, 0.993f, 1.02f, 1.072f, 1.199f, 1.262f, 1.319f, 1.47f };
static const float WYV_THRUST_N[] = { 0.0f, 68.694f, 65.879f, 62.5f, 51.802f, 43.356f, 31.532f, 29.279f, 23.086f, 9.572f, 4.505f, 2.815f, 0.0f };
#define WYV_THRUST_NPTS    13
#define WYV_IMPULSE_NS     55.87f    // trapezoid integral of the table above

// ------------------------------------------------------------------------------------- arming button
// 6 mm tactile switch (Adafruit 367) in a printed cradle on the -Y control-tube wall, its plunger
// 0.3 mm under a 4 mm hole; press it with a pen or toothpick. Pin to GND, internal pull-up.
//   PAD   : hold >= 2 s -> LED solid; let go, hands off -> 1 s settle -> IMU zeroed -> ARMED.
//           Arming is refused (fast blink 3 s) if the SD log is not open, the IMU is stale,
//           the pack is below WYV_VBAT_WARN, or the rocket is more than WYV_ARM_TILT_MAX_DEG off vertical.
//   ARMED : hold >= 2 s -> back to PAD (fins stay neutral in flight).
// A 3 mm red LED (SparkFun COM-00533, 220 ohm to GND) shows through a 3.2 mm hole next to the button.
#define WYV_PIN_BUTTON       14        // GP14
#define WYV_PIN_LED_EXT      15        // GP15
#define WYV_ARM_HOLD_MS      2000
#define WYV_ARM_SETTLE_MS    1000
#define WYV_ARM_STILL_DPS    3.0f      // |w| must stay under this during the settle window
#define WYV_ARM_TILT_MAX_DEG 20.0f     // launch-rail angle allowed (gravity vs body Z)

// ------------------------------------------------------------------------------------- servos
// 4 x EMAX ES9251 II (digital, 4.5-6.0 V; rev 3f) on their own 5 V MPM3610 rail, NOT the 2S pack, all four
// in ONE ring at the same station, each bolted by its ears to a pad in the control-tube wall, shaft radial.
// RP2350 PWM at 200 Hz with a 1 us count (analogWriteRange 5000). GP10/GP11 are slice 5 A/B, GP12/GP13
// slice 6 A/B. EMAX does not publish a frame-rate limit: VERIFY on the bench (t2). If a servo buzzes or
// jitters at 200 Hz, set WYV_SERVO_HZ 50 and WYV_SERVO_RANGE 20000.
#define WYV_SERVO_HZ       200
#define WYV_SERVO_RANGE    5000      // counts per period -> 1 count = 1 us at 200 Hz
// Fin index: 0 = A+ (az 0, +X)   1 = A- (az 180, -X)   2 = B+ (az 90, +Y)   3 = B- (az 270, -Y)
// A-pair spans the X axis and makes force along Y (controls rotation about X, "axis A").
// B-pair spans the Y axis and makes force along X (controls rotation about Y, "axis B").
static const uint8_t  WYV_PIN_SERVO[4]   = { 10, 11, 12, 13 };   // GP10..GP13
static const int16_t  WYV_SERVO_TRIM[4]  = { 0, 0, 0, 0 };        // us, set on the bench (fin square to body)
static const int8_t   WYV_SERVO_SIGN[4]  = { +1, -1, +1, -1 };    // mirrored mounting; confirm with t2 test
#define WYV_SERVO_CENTER_US   1500
#define WYV_SERVO_US_PER_DEG  10.0f   // EMAX neutral 1500 us; calibrate deg-per-us with the angle gauge (t2)
#define WYV_DEFL_MAX_DEG      15.0f   // mechanical/aero limit (sim + CFD)
#define WYV_DEFL_RATE_DPS     450.0f  // slew cap well below the ES9251 II 0.08 s/60 deg (4.8 V) no-load speed

// ------------------------------------------------------------------------------------- misc I/O
// RP2350 ADC inputs are 3.3 V max: 8.4 V full pack -> 2.69 V at the pin.
#define WYV_PIN_VBAT       26        // GP26 / ADC0: 2S pack through 100k/47k divider (+100 nF)
#define WYV_VBAT_RATIO     (147.0f / 47.0f)
#define WYV_VBAT_WARN      6.8f
#define WYV_VBAT_CRIT      6.4f
#define WYV_PIN_LED        WYV_PIN_LED_EXT   // the Pico 2 W's own LED hangs off the CYW43 radio chip; leave it (and the radio) off
#define WYV_USB_TLM_HZ     10        // tagged CSV over USB serial when a host is attached (bench / pad check)

// ------------------------------------------------------------------------------------- control law
// delta[rad] = S(qbar) * ( KP*theta + KI*int(theta) + KD*omega ),  S = clamp(Q_REF/qbar, S_MIN, S_MAX)
// theta = tilt about the axis (rad, + = nose toward +Y for axis A, toward +X for axis B)
// delta + = fin force toward + of the same axis at the fin station (aft of CG) -> restoring.
#define WYV_KP             4.5f
#define WYV_KI             1.0f
#define WYV_KD             0.8f      // wf_flightsim --retune (rev 3d airframe keeps 4.5 / 1.0 / 0.8)
#define WYV_Q_REF_PA       1500.0f
#define WYV_SCHED_MIN      0.15f
#define WYV_SCHED_MAX      4.0f
#define WYV_INTEG_LIM      0.20f     // rad*s
#define WYV_AXIS_B_SCALE   1.00f     // both pairs share one station -> identical arms; keep the hook for asymmetry
#define WYV_ROLL_KD        0.020f    // rad per (rad/s) of roll rate, differential deflection
#define WYV_ROLL_DEFL_MAX  5.0f      // deg of the 15 deg budget reserved for roll damping
#define WYV_CTRL_HZ        200

// ------------------------------------------------------------------------------------- flight phases
#define WYV_LAUNCH_G           3.0f      // |a| threshold, sustained...
#define WYV_LAUNCH_SUSTAIN_MS  50
#define WYV_RAIL_CLEAR_MS      250       // F42-4T leaves the 6 ft rail at 0.23 s (wf_flightsim)
#define WYV_BURN_MS            1470      // F42-4T burn (AeroTech .eng, thrustcurve.org); 920 for the F67-6W
#define WYV_CTRL_END_QBAR      15.0f     // Pa: rev 3d keeps the fins flying in coast until q drops below this
                                         // (was: climb rate < 15 m/s, which stopped ~1.5 s before apogee)
#define WYV_ABORT_TILT_DEG     30.0f     // fins to neutral (passively stable) beyond this tilt
#define WYV_EJECT_MS           (WYV_BURN_MS + 4000UL)  // F42-4T ejection (4 s delay), logged only

// Authority monitor (RQ3 + safety): least-squares fit of omega_dot = b * delta over a sliding window
// right after rail exit. If the fitted control effectiveness has the wrong sign with confidence,
// the fins go to neutral for the rest of the flight (the airframe is passively stable).
#define WYV_AUTH_WINDOW_MS     150
#define WYV_AUTH_MIN_EXCITE    0.02f     // rad of delta RMS needed before the fit is trusted
#define WYV_AUTH_TSTAT_ABORT   -3.0f     // t-statistic of b below which we abort control

// Authority-demonstration manoeuvre (mirrors wf_flightsim.MAN / MAN_GATE). Runs once, in coast:
//   t_man0 = burnout + 250 ms, then (ms after t_man0)
//     0    doublet axis A, +/-5 deg on top of the PID, 120 ms each half  -> M_delta/I (least squares)
//     400  doublet axis B
//     800  attitude step axis A, 1 deg from wherever it is, 500 ms hold, 400 ms back to the hold
//     1700 attitude step axis B
//   Gates at t_man0: qbar >= 800 Pa, tilt <= 10 deg, altitude >= 30 m, control healthy.
//   Step direction: the one that lowers the pair's current deflection (a crosswind already has the
//   fins working). A step is skipped if the pair is already beyond 14 deg.
//   Abort (programme dropped, plain tilt-hold resumes): attitude > 8 deg from where it started.
// The sim predicts (rev 3d, F42-4T, H45 fins, 20 mm stabilizers): doublet A at ~1.2 kPa,
// M_delta/I = 40 1/s^2 per rad; fit/model 0.95 +/- 0.10 (1 sd over 40 flights, wind 0-7 m/s);
// step t63 0.15 +/- 0.01 s, 0.98 +/- 0.11 deg achieved. See plots_flight/maneuver_prediction.json.
#define WYV_MAN_ENABLE         1
#define WYV_MAN_T0_MS          (WYV_BURN_MS + 250)
#define WYV_MAN_DOUBLET_DEG    5.0f
#define WYV_MAN_DOUBLET_HALF   120
#define WYV_MAN_FIT_TAIL_MS    160
#define WYV_MAN_STEP_DEG       1.0f
#define WYV_MAN_HOLD_MS        500
#define WYV_MAN_REST_MS        400
#define WYV_MAN_OFF_DA         0
#define WYV_MAN_OFF_DB         400
#define WYV_MAN_OFF_SA         800
#define WYV_MAN_OFF_SB         1700
#define WYV_MAN_QBAR_MIN       800.0f
#define WYV_MAN_TILT_MAX_DEG   10.0f
#define WYV_MAN_ALT_MIN_M      30.0f
#define WYV_MAN_DEV_ABORT_DEG  8.0f
#define WYV_MAN_HEADROOM_DEG   14.0f
// Model control derivative per unit dynamic pressure, (M_delta / I) / qbar, at burnout mass
// (wf_flightsim, b_per_q). The firmware logs b_fit / (WYV_B_PER_Q * qbar) as the authority ratio.
#define WYV_B_PER_Q            0.0354f    // rev 4b airframe, mean of axes A/B (plots_flight/maneuver_prediction.json)

// ------------------------------------------------------------------------------------- logging
#define WYV_LOG_HZ_SD      100       // the 4682 microSD on SPI0 is the only record
#define WYV_LOG_PREALLOC_MB 128      // contiguous pre-allocation: 96 B x 100 Hz -> ~3.8 h of pad + flight
#define WYV_LOG_RING_BYTES  32768    // RAM ring buffer; written out 512 B at a time only when the card is idle
