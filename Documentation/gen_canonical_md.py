#!/usr/bin/env python3
"""Regenerate CANONICAL_NUMBERS.md from the sim outputs (run after the cascade)."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); SIM = os.path.join(HERE, "..", "Simulations")
sys.path.insert(0, SIM); import wf_core as C
can = json.load(open(os.path.join(SIM, "canonical_numbers.json")))
fl = json.load(open(os.path.join(SIM, "plots_flight", "flight_summary.json")))
au = json.load(open(os.path.join(SIM, "plots_authority", "authority_matrix.json")))
pw = json.load(open(os.path.join(SIM, "plots_power", "battery_budget.json")))
lk = json.load(open(os.path.join(SIM, "plots_link", "link_budget.json")))
bp = json.load(open(os.path.join(SIM, "plots_bypass", "bypass_trade.json")))
mr = json.load(open(os.path.join(HERE, "..", "3D parts", "_generator", "mass_report.json")))
FM = C.FLIGHT_MOTOR
g = can["vehicles"][FM]; on = fl[FM]["control_on"]; off = fl[FM]["control_off"]
st = C.stability(g["cg_liftoff_mm"]); st0 = C.stability(g["cg_liftoff_mm"], interference=False)
printed = sum(p["mass_g"] for p in mr["parts"] if p["flight"])
b05 = [r for r in bp["results"]["0.5"] if abs(r["d_mm"] - C.BYPASS["id"]) < 0.01][0] if "0.5" in bp["results"] else None
L = []
a = L.append
a("# GTR70E WYVERN fin-control — canonical numbers\n")
a("_Generated by `Documentation/gen_canonical_md.py` from the simulation outputs. Do not edit by hand; re-run the cascade (root README)._\n")
a("## Vehicle\n\n| | value |\n|---|---|")
for k, v in [("Overall length / OD", f"{C.L_TOTAL:.0f} mm / {C.OD:.0f} mm"),
             ("Sections", f"nose {C.NOSE['L']:.0f} · recovery bay {C.L_RB:.0f} · control tube {C.L_CT:.0f} · motor bay {C.L_MB:.0f} mm"),
             (f"Liftoff / burnout ({FM})", f"{g['liftoff_g']:.0f} g / {g['burnout_g']:.0f} g"),
             ("Printed parts / ballast", f"{printed:.0f} g / {C.BALLAST_G:.0f} g"),
             ("CG liftoff / burnout", f"{g['cg_liftoff_mm']:.0f} / {g['cg_burnout_mm']:.0f} mm"),
             ("CP (interference counted)", f"{st['xcp']:.0f} mm"),
             ("Static margin liftoff / burnout", f"{g['margin_liftoff_cal']:.2f} / {g['margin_burnout_cal']:.2f} cal (no interference: {st0['margin_cal']:.2f})"),
             ("Pitch inertia", f"{g['Iyy_kgm2']:.4f} kg m²"),
             ("Control hinge A / B (station)", f"{C.X_HINGE_A:.0f} / {C.X_HINGE_B:.0f} mm; arm aft of CG {g['arm_A_mm']:.0f} / {g['arm_B_mm']:.0f} mm"),
             ("Control fins", f"triangular, root {C.CFIN['root']:.0f} mm, hinge {C.CFIN['hinge_frac']*100:.0f} % chord, H* = {C.CFIN_H_NOMINAL:.0f} mm, ±{C.CFIN['defl_max_deg']:.0f}°"),
             ("Stabilizers (fixed fins)", f"4 x {C.RECT_FIN['root']:.0f} x {C.RECT_FIN['span']:.0f} x {C.RECT_FIN['t']} mm at 45°"),
             ("Servo", f"{C.SERVO['name']}, base r = {C.SERVO_BASE_R:.1f} mm, spline tip r = {C.SPLINE_TOP_R:.1f} mm"),
             ("Bypass tube", f"{C.BYPASS['od']} x {C.BYPASS['id']} mm Al, {C.BYPASS['L']:.0f} mm, {C.bypass_mass():.1f} g, on the vehicle centreline")]:
    a(f"| {k} | {v} |")
a(f"\n## Flight ({FM}, 4 m/s wind + 4 m/s gust)\n\n| | control on | fins locked |\n|---|---|---|")
for k, key, fmt in [("Rail exit speed (6 ft)", "rail_exit_v", "{:.1f} m/s"), ("Burnout speed", "v_burnout", "{:.0f} m/s"), ("Max q", "max_q_Pa", "{:.0f} Pa"),
                    ("Apogee", "apogee_m", "{:.0f} m"), ("Time to apogee", "t_apogee", "{:.2f} s"), ("RMS tilt rail exit → burnout+2 s", "tilt_rms_deg", "{:.1f}°"),
                    ("Max tilt", "tilt_max_deg", "{:.1f}°"), ("Drift at apogee", "drift_m", "{:.0f} m"), ("Peak hinge moment", "max_hinge_Nm", "{:.3f} N m")]:
    a(f"| {k} | {fmt.format(on[key])} | {fmt.format(off[key])} |")
a(f"\nT/W {g['TW_avg']} avg / {g['TW_peak']} peak · ideal delay {fl[FM]['optimal_delay_s']} s → pick {fl[FM]['delay_pick']} s · gains {fl['gains']}")
a("\n## Motor options (all 29 x 83 mm single-use, no certification)\n\n| motor | impulse (N s) | liftoff (g) | rail exit (m/s) | apogee (m) | RMS tilt on / locked | delay pick | cost note |\n|---|---|---|---|---|---|---|---|")
for mk in C.MOTORS:
    r = fl[mk]
    a(f"| {mk} | {C.MOTORS[mk]['I']:.1f} | {r['liftoff_g']:.0f} | {r['control_on']['rail_exit_v']:.1f} | {r['control_on']['apogee_m']:.0f} | {r['control_on']['tilt_rms_deg']:.1f}° / {r['control_off']['tilt_rms_deg']:.1f}° | {r['delay_pick']} s | {C.MOTORS[mk]['note'].split(';')[-1].strip()} |")
a("\n## Control authority (NACA 0006, pessimistic interference)\n\n| H (mm) | interference | Cmδ isolated | Cmδ installed A | Cmδ installed B | RMS tilt (sim) |\n|---|---|---|---|---|---|")
cl = {c["H_mm"]: c for c in au["closed_loop"]["NACA0006"]}
for r in au["rows"]:
    if r["profile"] == "NACA0006":
        a(f"| {r['H_mm']:.0f} | {r['interference_ratio']:.3f} | {r['Cmd_isolated_A']:.2f} | {r['Cmd_net_A']:.2f} | {r['Cmd_net_B']:.2f} | {cl[r['H_mm']]['tilt_rms']:.1f}° |")
a(f"\nSelection: {au['selection']['NACA0006']}")
a("\n## Electronics\n\n| | |\n|---|---|")
a(f"| Pad idle / flight current | {pw['idle_mA']:.0f} mA / {pw['flight_mA']:.0f} mA |")
a(f"| Mission charge / derated requirement / pack | {pw['mission_mAh']:.1f} / {pw['required_with_derating_mAh']:.0f} / {pw['pack_mAh']} mAh ({pw['margin_x']:.1f}x) |")
a(f"| LoRa | SF{lk['config']['sf']}/{lk['config']['bw']/1e3:.0f} kHz, {lk['payload_B']} B, {lk['time_on_air_ms']:.1f} ms, {lk['flight_rate_Hz']} Hz, margin {lk['margin_at_slant_dB']:.0f} dB at {lk['worst_slant_m']:.0f} m |")
if b05:
    b03 = [r for r in bp["results"]["0.3"] if abs(r["d_mm"] - C.BYPASS["id"]) < 0.01][0]
    a(f"\n## Ejection (chosen tube)\n\n0.3 g BP: bay {b03['peak_bay_kPa']:.0f} kPa → {b03['nose_force_peak_N']:.0f} N push vs {bp['release_force_N']:.0f} N release; plenum {b03['peak_plenum_kPa']:.0f} kPa, kick-out {b03['motor_kickout_N']:.0f} N")
    a(f"\n0.5 g BP: bay {b05['peak_bay_kPa']:.0f} kPa → {b05['nose_force_peak_N']:.0f} N push vs {bp['release_force_N']:.0f} N release; plenum {b05['peak_plenum_kPa']:.0f} kPa, kick-out {b05['motor_kickout_N']:.0f} N")
_sp = os.path.join(C.HERE, "plots_stabilizer", "stabilizer_sweep.json")
if os.path.exists(_sp):
    sj = json.load(open(_sp))
    a(f"\n## SQ1: stabilizer span and azimuth (H = 40, {FM}, pessimistic interference)\n\n| offset | span (mm) | margin liftoff (cal) | interference | installed / isolated | RMS tilt active / locked |\n|---|---|---|---|---|---|")
    for r in sj["rows"]:
        if r["offset_deg"] == 45.0 or r["span_mm"] == C.RECT_FIN["span"]:
            cl = f"{r['tilt_rms_ctrl']:.1f}° / " + (f"{r['tilt_rms_locked']:.1f}°" if r['tilt_rms_locked'] < 90 else "tumbles") if "tilt_rms_ctrl" in r else "—"
            a(f"| {r['offset_deg']:g}° | {r['span_mm']:.0f} | {r['SM_liftoff_cal']:.2f} | {r['interference_ratio']:.3f} | {r['installed_over_isolated']:.2f} | {cl} |")
    a("\nTunnel Phase B prediction (one pair at 10°, " + f"{sj['V_tunnel_B']:g} m/s): " + "; ".join(
        f"H{int(x['H_mm'])} off {x['N_off_mN']:.1f} mN" + "".join(f", {k} {sj['tunnel_phase_b'][k][i]['N_on_mN']:.1f} mN" for k in sj['tunnel_phase_b'])
        for i, x in enumerate(sj['tunnel_phase_b'][next(iter(sj['tunnel_phase_b']))])))
open(os.path.join(HERE, "CANONICAL_NUMBERS.md"), "w").write("\n".join(L) + "\n"); print("wrote CANONICAL_NUMBERS.md")
